// ─────────────────────────────────────────────────────────────────────────────
// Matching Engine
// Score each protocol against the captured signal features.
// Returns 0–100 confidence.
// ─────────────────────────────────────────────────────────────────────────────

static uint8_t score_protocol(const SignalCapture* cap, const ProtocolSignature* proto) {
    uint32_t score   = 0;
    uint32_t max_pts = 0;

    // ── Frequency (35 points — most important) ──────────────────────────────
    max_pts += 35;
    if(cap->frequency >= proto->freq_min && cap->frequency <= proto->freq_max) {
        score += 35;
    } else {
        // Partial: within 2x the band width
        uint32_t centre = proto->freq_min / 2 + proto->freq_max / 2;
        uint32_t span   = proto->freq_max - proto->freq_min;
        uint32_t delta  = (cap->frequency > centre)
                          ? cap->frequency - centre
                          : centre - cap->frequency;
        if(delta < span) score += 15;
    }

    // ── Modulation (25 points) ───────────────────────────────────────────────
    max_pts += 25;
    if(cap->modulation == proto->modulation) {
        score += 25;
    } else if(proto->modulation == ModulationUnknown || cap->modulation == ModulationUnknown) {
        score += 8; // partial when one side is unknown
    }

    // ── Pulse width (20 points) ──────────────────────────────────────────────
    max_pts += 20;
    // FM / LoRa entries don't use pulse_min/max in the same way
    if(proto->pulse_min > 0 && proto->pulse_max > 0) {
        if(cap->pulse_avg >= proto->pulse_min && cap->pulse_avg <= proto->pulse_max) {
            score += 20;
        } else if(cap->pulse_avg >= proto->pulse_min * 7 / 10 &&
                  cap->pulse_avg <= proto->pulse_max * 13 / 10) {
            score += 10; // close enough
        }
    } else {
        score += 10; // not enough data to penalise
        max_pts -= 10;
    }

    // ── Repetition (10 points) ───────────────────────────────────────────────
    max_pts += 10;
    if(cap->repeating == proto->repeating) {
        score += 5;
        if(proto->repeating && proto->repeat_min > 0 &&
           cap->repeat_count >= proto->repeat_min) {
            score += 5;
        } else if(!proto->repeating) {
            score += 5;
        }
    }

    // ── Bandwidth (10 points) ────────────────────────────────────────────────
    max_pts += 10;
    if(proto->bandwidth_khz > 0) {
        int16_t bw_delta = (int16_t)cap->bandwidth_khz - (int16_t)proto->bandwidth_khz;
        if(bw_delta < 0) bw_delta = -bw_delta;
        if(bw_delta < 20)       score += 10;
        else if(bw_delta < 60)  score += 5;
    } else {
        max_pts -= 10; // don't penalise unknown bandwidth
    }

    // ── Confidence bonus ─────────────────────────────────────────────────────
    score   += proto->confidence_bonus;
    max_pts += proto->confidence_bonus;

    if(max_pts == 0) return 0;
    uint32_t pct = (score * 100) / max_pts;
    return (uint8_t)(pct > 100 ? 100 : pct);
}

bool protocol_db_match(const SignalCapture* cap, ProtocolMatch* out) {
    out->matched   = false;
    out->protocol  = NULL;
    out->confidence = 0;
    out->decoded[0] = '\0';
    out->conf_label[0] = '\0';

    uint8_t best_conf  = 0;
    int16_t best_index = -1;

    for(uint16_t i = 0; i < DB_COUNT; i++) {
        uint8_t conf = score_protocol(cap, &DB[i]);
        if(conf > best_conf) {
            best_conf  = conf;
            best_index = (int16_t)i;
        }
    }

    if(best_index >= 0 && best_conf >= MIN_CONFIDENCE) {
        out->matched    = true;
        out->protocol   = &DB[best_index];
        out->confidence = best_conf;
        if(best_conf >= 80)      snprintf(out->conf_label, sizeof(out->conf_label), "High");
        else if(best_conf >= 60) snprintf(out->conf_label, sizeof(out->conf_label), "Medium");
        else                     snprintf(out->conf_label, sizeof(out->conf_label), "Low");
        return true;
    }

    snprintf(out->conf_label, sizeof(out->conf_label), "No match");
    return false;
}

// ─────────────────────────────────────────────────────────────────────────────
// Decoder — fills decoded[] with human-readable data extracted from the signal.
// Real decoding would parse raw_pulses; here we provide best-effort summaries.
// ─────────────────────────────────────────────────────────────────────────────

void protocol_db_decode(const SignalCapture* cap, ProtocolMatch* match) {
    if(!match->matched || !match->protocol) return;
    const ProtocolSignature* p = match->protocol;
    char* buf = match->decoded;
    int   len = DECODED_LEN;
    int   pos = 0;

    // Signal stats always shown
    pos += snprintf(buf + pos, len - pos,
        "RSSI:     %.0f dBm\n"
        "Noise:    %.0f dBm\n"
        "SNR:      %.1f dB\n"
        "Pulses:   %u\n"
        "Bits:     ~%u\n"
        "Repeats:  %u\n",
        (double)cap->rssi, (double)cap->noise_floor, (double)cap->snr,
        cap->pulse_count, cap->packet_bits, cap->repeat_count);

    if(p->fixed_code)   pos += snprintf(buf+pos, len-pos, "Code:     Fixed\n");
    if(p->rolling_code) pos += snprintf(buf+pos, len-pos, "Code:     Rolling\n");
    pos += snprintf(buf+pos, len-pos, "Encrypt:  %s\n", p->encrypted ? "Yes" : "No");

    // ── Bit extraction from pulse timings ─────────────────────────────────────
    const uint32_t* pp   = cap->raw_pulses;
    uint16_t        pc   = cap->pulse_count;
    uint16_t        pavg = cap->pulse_avg > 0 ? cap->pulse_avg : 1;
    uint8_t         bytes[8] = {0};
    uint16_t        bit_count = 0;
    uint8_t         bits[64]  = {0};

    if(pc > 4) {
        for(uint16_t i = 1; i < pc && bit_count < 64; i++) {
            bits[bit_count++] = (pp[i] > (uint32_t)(pavg + pavg / 2)) ? 1 : 0;
        }
        for(uint8_t i = 0; i < 8 && i * 8 < bit_count; i++) {
            for(uint8_t j = 0; j < 8 && (i*8+j) < bit_count; j++) {
                bytes[i] = (uint8_t)(bytes[i] | (bits[i*8+j] << (7-j)));
            }
        }
    }

    // ── TPMS 315 MHz ─────────────────────────────────────────────────────────
    if(cap->frequency >= 314000000 && cap->frequency <= 316000000 && bit_count >= 48) {
        uint32_t sid  = ((uint32_t)bytes[0]<<24)|((uint32_t)bytes[1]<<16)|
                        ((uint32_t)bytes[2]<<8)|bytes[3];
        uint16_t kpa  = (uint16_t)bytes[5] * 25 / 10;
        int16_t  temp = (int16_t)bytes[6] - 40;
        float    psi  = (float)kpa / 6.895f;
        pos += snprintf(buf+pos, len-pos,
            "\n[TPMS]\nSensor: %08lX\nPres:   %d kPa / %.1f PSI\nTemp:   %d C\nBatt:   %s\n",
            (unsigned long)sid, kpa, (double)psi, temp,
            (bytes[4] & 0x04) ? "LOW" : "OK");
    }

    // ── TPMS 433 MHz FSK ─────────────────────────────────────────────────────
    if(cap->frequency >= 433000000 && cap->frequency <= 434000000
       && cap->modulation == ModulationFSK && pavg < 300 && bit_count >= 48) {
        uint32_t sid  = ((uint32_t)bytes[0]<<24)|((uint32_t)bytes[1]<<16)|
                        ((uint32_t)bytes[2]<<8)|bytes[3];
        uint16_t kpa  = (uint16_t)bytes[5] * 25 / 10;
        int16_t  temp = (int16_t)bytes[6] - 40;
        float    bar  = (float)kpa / 100.0f;
        float    psi  = (float)kpa / 6.895f;
        pos += snprintf(buf+pos, len-pos,
            "\n[TPMS]\nSensor: %08lX\nPres:   %d kPa / %.2f bar / %.1f PSI\nTemp:   %d C\n",
            (unsigned long)sid, kpa, (double)bar, (double)psi, temp);
    }

    // ── Oregon Scientific weather 433 MHz OOK ────────────────────────────────
    if(p->category == CategoryWeather
       && cap->frequency >= 433000000 && cap->frequency <= 434000000
       && cap->modulation == ModulationOOK && pavg >= 900 && bit_count >= 32) {
        int16_t raw  = (int16_t)((bytes[2]&0x0F)*100 + ((bytes[3]>>4)&0x0F)*10 + (bytes[3]&0x0F));
        if(bytes[4] & 0x08) raw = (int16_t)(-raw);
        uint8_t hum  = (uint8_t)(((bytes[4]&0x0F)*10) + ((bytes[5]>>4)&0x0F));
        pos += snprintf(buf+pos, len-pos,
            "\n[WEATHER]\nTemp:  %d.%d C\nHum:   %d%%\nBatt:  %s\n",
            raw/10, (raw<0 ? -raw : raw)%10, hum,
            (bytes[0]&0x04) ? "LOW" : "OK");
    }

    // ── Bresser 868 MHz weather FSK ──────────────────────────────────────────
    if(p->category == CategoryWeather
       && cap->frequency >= 868000000 && cap->frequency <= 869000000
       && bit_count >= 40) {
        int16_t raw_t  = (int16_t)(((uint16_t)bytes[2]<<8)|bytes[3]);
        float   temp_c = (float)(raw_t - 400) / 10.0f;
        uint8_t hum    = bytes[4];
        uint16_t ws_r  = (uint16_t)(((uint16_t)(bytes[5]&0x0F)<<8)|bytes[6]);
        float   wspd   = (float)ws_r / 10.0f;
        const char* wd[] = {"N","NNE","NE","ENE","E","ESE","SE","SSE",
                            "S","SSW","SW","WSW","W","WNW","NW","NNW"};
        pos += snprintf(buf+pos, len-pos,
            "\n[WEATHER]\nTemp:  %.1f C\nHum:   %d%%\nWind:  %.1f m/s %s\n",
            (double)temp_c, hum, (double)wspd, wd[bytes[7]&0x0F]);
    }

    // ── Utility meter wM-Bus 868 MHz ─────────────────────────────────────────
    if(p->category == CategoryUtility && bit_count >= 40) {
        uint16_t mid = (uint16_t)(((uint16_t)bytes[2]<<8)|bytes[3]);
        char m0 = (char)(((mid>>10)&0x1F)+64);
        char m1 = (char)(((mid>>5) &0x1F)+64);
        char m2 = (char)((mid      &0x1F)+64);
        uint32_t meter_id = ((uint32_t)bytes[4]<<24)|((uint32_t)bytes[5]<<16)|
                            ((uint32_t)bytes[6]<<8)|bytes[7];
        pos += snprintf(buf+pos, len-pos,
            "\n[METER]\nMfr:   %c%c%c\nID:    %08lX\nData:  Encrypted\n",
            m0, m1, m2, (unsigned long)meter_id);
    }

    // ── POCSAG pager ─────────────────────────────────────────────────────────
    if(p->category == CategoryIndustrial && pavg >= 50 && pavg <= 54 && bit_count >= 32) {
        uint32_t cw  = ((uint32_t)bytes[0]<<24)|((uint32_t)bytes[1]<<16)|
                       ((uint32_t)bytes[2]<<8)|bytes[3];
        uint32_t cap_code = (cw >> 13) & 0x7FFFF;
        const char* fn[] = {"Numeric","Unknown","Alpha","Tone"};
        pos += snprintf(buf+pos, len-pos,
            "\n[POCSAG]\nCAP:   %lu\nFunc:  %s\n",
            (unsigned long)cap_code, fn[(cw>>11)&0x03]);
    }

    // ── Generic extra data ────────────────────────────────────────────────────
    if(p->extra_data && pos < len-2)
        pos += snprintf(buf+pos, len-pos, "\nDECODABLE:\n%s\n", p->extra_data);

    if(p->needs_esp32 && pos < len-2)
        pos += snprintf(buf+pos, len-pos, "\n[!] Needs ESP32 for full decode\n");

    if(p->security_concern && pos < len-2)
        pos += snprintf(buf+pos, len-pos, "\n[!] SECURITY:\n%s\n", p->security_note);
}
